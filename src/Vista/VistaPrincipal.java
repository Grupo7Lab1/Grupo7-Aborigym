private void abrirVentana(javax.swing.JInternalFrame ventana) {
    for (javax.swing.JInternalFrame f : jDesktopPanel.getAllFrames()) {
        if (f.getClass().equals(ventana.getClass())) {
            try {
                f.setSelected(true);
            } catch (java.beans.PropertyVetoException ex) {
                logger.log(java.util.logging.Level.WARNING, null, ex);
            }
            return;
        }
    }
    jDesktopPanel.add(ventana);
    ventana.setLocation(20, 20);
    ventana.setVisible(true);
}
