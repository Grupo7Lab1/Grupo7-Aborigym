    private void jBAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBAgregarActionPerformed
        if (jCBSocio.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Seleccioná un socio.");
            return;
        }

        if (jDCFechaDeInicio.getDate() == null
                || jDCFechaDeFinalizacion.getDate() == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Seleccioná las dos fechas.");
            return;
        }

        java.time.LocalDate inicio = jDCFechaDeInicio.getDate()
                .toInstant()
                .atZone(java.time.ZoneId.systemDefault())
                .toLocalDate();

        java.time.LocalDate fin = jDCFechaDeFinalizacion.getDate()
                .toInstant()
                .atZone(java.time.ZoneId.systemDefault())
                .toLocalDate();

        if (fin.isBefore(inicio)) {
            javax.swing.JOptionPane.showMessageDialog(this, "La fecha de finalización no puede ser anterior al inicio.");
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this, "Validación correcta. El siguiente paso es guardar el pase.");
    }//GEN-LAST:event_jBAgregarActionPerformed

    private void jBModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBModificarActionPerformed
        int fila = jTPases.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Seleccioná un pase de la tabla para modificarlo."
            );
            return;
        }

        if (jCBSocio.getSelectedItem() == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Seleccioná un socio."
            );
            return;
        }

        if (jDCFechaDeInicio.getDate() == null
                || jDCFechaDeFinalizacion.getDate() == null) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Seleccioná las fechas de inicio y finalización."
            );
            return;
        }

        java.time.LocalDate inicio = jDCFechaDeInicio.getDate()
                .toInstant()
                .atZone(java.time.ZoneId.systemDefault())
                .toLocalDate();

        java.time.LocalDate fin = jDCFechaDeFinalizacion.getDate()
                .toInstant()
                .atZone(java.time.ZoneId.systemDefault())
                .toLocalDate();

        if (fin.isBefore(inicio)) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "La fecha de finalización no puede ser anterior a la fecha de inicio."
            );
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Validación correcta. El siguiente paso es actualizar el pase."
        );
    }//GEN-LAST:event_jBModificarActionPerformed

    private void jBEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBEliminarActionPerformed
        int fila = jTPases.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Seleccioná un pase de la tabla para eliminarlo."
            );
            return;
        }

        int confirmacion = javax.swing.JOptionPane.showConfirmDialog(
                this, "¿Estás seguro de que querés eliminar este pase?", "Confirmar eliminación",
                javax.swing.JOptionPane.YES_NO_OPTION,
                javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (confirmacion != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        javax.swing.JOptionPane.showMessageDialog(this, "Confirmación correcta. El siguiente paso es eliminar el pase de la base de datos."
        );
    }//GEN-LAST:event_jBEliminarActionPerformed

